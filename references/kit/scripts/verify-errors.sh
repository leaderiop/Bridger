#!/usr/bin/env bash
# verify-errors.sh — the error catalog against the sources (improvement report 05, R3; BEH-KT-049..052).
#
# Usage: bash references/kit/scripts/verify-errors.sh [--write]
#
# Requires bash and python3 (standard library only). Four sets of error tags are extracted:
#   spec     every `TaggedError<X>()("X"` and `Data.TaggedError("X")` in references/**/*.md (the behaviours define them);
#   proto    the same in prototypes/**/src/*.ts;
#   table    the rows of the BEH-KT-052 tables in references/kit/behaviors/07-error-catalog.md;
#   guide    the `### Tag` headings of docs/guides/error-catalog.md.
# Fails on: a spec or prototype tag with no row in the table; a table row with no heading in the guide and the reverse;
# a table row whose tag no other file mentions (a tag that no longer exists); a prototype/src/errors.catalog.ts that differs from what the table and the sources generate (--write regenerates it). Tags a row names that no source declares are listed, not failed:
# several rows describe record-only tags and ports the specifications name in prose. DOC_ERRORS_EXTRA is a fixture hook.
set -euo pipefail
SPEC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "$SPEC_DIR/../.." && pwd)"
exec python3 - "$REPO_ROOT" "${1:-}" <<'PY'
import json, os, re, sys
ROOT, ARG = sys.argv[1], sys.argv[2]
def read(p):
    with open(p, encoding="utf-8") as f: return f.read()
def walk(base, ext):
    for d, ds, fs in os.walk(base):
        ds[:] = sorted(x for x in ds if x not in ("node_modules", ".git", "dist", ".doc-snippets"))
        for f in sorted(fs):
            if f.endswith(ext): yield os.path.join(d, f)
DECL = re.compile(r'(?:Schema|Data)\.TaggedError(?:Class)?(?:<\w+>\(\))?\(\s*"([A-Z]\w+)"|extends Error \{ readonly _tag = "([A-Z]\w+)"')
tagsof = lambda text: [a or b for a, b in DECL.findall(text)]
extra = os.environ.get("DOC_ERRORS_EXTRA", "")
spec, proto, hc = {}, {}, {}
for p in walk(os.path.join(ROOT, "references"), ".md"):
    for t in tagsof(read(p)): spec.setdefault(t, p)
for p in walk(os.path.join(ROOT, "prototypes"), ".ts"):
    if "/src/" in p:
        for t in tagsof(read(p)):
            proto.setdefault(t, p)
            if "/host-core/src/" in p: hc.setdefault(t, p)
if extra:
    for p in walk(extra, ".ts"):
        for t in tagsof(read(p)): proto.setdefault(t, p)
cat = read(os.environ.get("DOC_ERRORS_TABLE", os.path.join(ROOT, "references", "kit", "behaviors", "07-error-catalog.md")))
table = {t for row in re.findall(r'^\| ((?:`[A-Z]\w+`(?:, )?)+) \|', cat, re.M) for t in re.findall(r'[A-Z]\w+', row)}   # a row may group tags
guide_path = os.environ.get("DOC_ERRORS_GUIDE", os.path.join(ROOT, "docs", "guides", "error-catalog.md"))
guide = {t for h in re.findall(r'^### (.+)$', read(guide_path), re.M) for t in re.findall(r'[A-Z]\w+', h)}   # a heading may group tags: `### A, B`
rel = lambda p: os.path.relpath(p, ROOT) if p.startswith(ROOT) else p
fails = []
for t, p in sorted({**spec, **proto}.items()):
    if t not in table: fails.append(f"{rel(p)}: error tag {t} has no row in BEH-KT-052 (07-error-catalog.md)")
for t in sorted(table - guide): fails.append(f"BEH-KT-052 row {t} has no entry in docs/guides/error-catalog.md")
for t in sorted(guide - table): fails.append(f"docs/guides/error-catalog.md entry {t} has no row in BEH-KT-052")
# the data file: one entry per tag the prototype declares, from the table's row
rows = {}
for m in re.finditer(r'^\| ((?:`[A-Z]\w+`(?:, )?)+) \| (.*)$', cat, re.M):
    cells = [c.strip() for c in m.group(2).rstrip('|').split(' | ')]
    for n in re.findall(r'[A-Z]\w+', m.group(1)): rows.setdefault(n, cells)
mods = sorted({os.path.basename(p)[:-3] for p in hc.values() if not p.endswith("errors.catalog.ts")})
CATALOG = os.path.join(ROOT, "prototypes", "host-core", "src", "errors.catalog.ts")
def generate():
    ns = lambda m: m.replace("-", "_") + "_"
    out = ["// GENERATED by references/kit/scripts/verify-errors.sh --write. The error catalog as data for the tags the prototype declares",
           "// (improvement report 05 R3, BEH-KT-049): one entry per tag, taken from its row in references/kit/behaviors/07-error-catalog.md.",
           "// A tag added to the prototype without an entry is a compile error here; an entry that differs from the table fails the script."]
    out += [f'import type * as {ns(m)} from "./{m}.js"' for m in mods]
    out += ["", "type TagOf<M> = { readonly [K in keyof M]: M[K] extends abstract new (...a: any) => { readonly _tag: infer T } ? T : never }[keyof M]",
            "export type ErrorTag = " + " | ".join(f"TagOf<typeof {ns(m)}>" for m in mods),
            "export interface Entry { readonly kind: string; readonly raisedBy: string; readonly cause: string; readonly fix: string }",
            "export const entries = {"]
    for t in sorted(t for t in hc if t in rows):
        r = rows[t]; kind, rb, ca, fx = r if len(r) == 4 else r[1:]
        out.append(f"  {t}: {{ kind: {json.dumps(kind)}, raisedBy: {json.dumps(rb)}, cause: {json.dumps(ca)}, fix: {json.dumps(fx)} }},")
    out.append("} as const satisfies Record<ErrorTag, Entry>")
    return "\n".join(out) + "\n"
if not extra:
    if ARG == "--write": open(CATALOG, "w", encoding="utf-8").write(generate())
    elif not os.path.exists(CATALOG) or read(CATALOG) != generate(): fails.append("prototypes/host-core/src/errors.catalog.ts is stale; run `bash references/kit/scripts/verify-errors.sh --write` and commit it")
corpus = ""
for base, exts in ((os.path.join(ROOT, "references"), (".md", ".yaml")), (os.path.join(ROOT, "docs"), (".md",)), (os.path.join(ROOT, "prototypes", "host-core", "src"), (".ts",))):
    for p in (q for e in exts for q in walk(base, e)):
        if p.endswith(("07-error-catalog.md", "guides/error-catalog.md")) or "improvement-reports" in p: continue
        corpus += read(p)
if not extra and "DOC_ERRORS_TABLE" not in os.environ:
    for t in sorted(table):
        if not re.search(r"\b" + t + r"\b", corpus): fails.append(f"BEH-KT-052 row {t} names a tag that no other file mentions (a tag that no longer exists?)")
named = sorted(table - set(spec) - set(proto))
print(f"verify-errors: {len(set(spec) | set(proto))} declared tags, {len(table)} table rows, {len(guide)} guide entries; {len(named)} row(s) name a tag no source declares")
for x in fails: print("[FAIL   ]", x)
print(f"{len(fails)} failure(s)")
sys.exit(1 if fails else 0)
PY
