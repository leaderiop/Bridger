// Spec-to-code correspondence (report 07, R2): which behaviour and invariant ids the prototype names.
//   node scripts/gen-correspondence.mjs            regenerate references/core/correspondence.md
//   node scripts/gen-correspondence.mjs --check    fail on a stale file, a dangling id or a coverage drop
//   node scripts/gen-correspondence.mjs --ratchet  raise the committed baseline to today's counts
// A citation is any `BEH-XX-nnn` / `INV-XX-nnn` in src/ or test/. Test files give the nearest it()/test() title.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const here = new URL(".", import.meta.url).pathname
const proto = join(here, "..")
export const root = join(proto, "..", "..")
const out = join(root, "references", "core", "appendices", "correspondence.md")
const baselinePath = join(root, "references", "core", "correspondence.baseline.json")

const walk = (dir, keep) => readdirSync(dir).sort().flatMap((n) => {
  const p = join(dir, n)
  return statSync(p).isDirectory() ? (n === "node_modules" ? [] : walk(p, keep)) : keep(p) ? [p] : []
})

const idRe = /\b(?:BEH|INV)-[A-Z]+-\d{3}\b/g
const defRe = /^#{2,3} ((?:BEH|INV)-[A-Z]+-\d{3}):/gm

export function collect() {
  const defined = new Set()
  for (const f of walk(join(root, "references"), (p) => p.endsWith(".md")))
    for (const m of readFileSync(f, "utf8").matchAll(defRe)) defined.add(m[1])
  const cites = new Map() // id -> {src?: "file:line", test?: "file:line title"}
  for (const side of ["src", "test"]) {
    for (const f of walk(join(proto, side), (p) => p.endsWith(".ts") || p.endsWith(".tsx"))) {
      const lines = readFileSync(f, "utf8").split("\n")
      let title = ""
      lines.forEach((line, i) => {
        const t = /\b(?:it|test)(?:\.\w+)?\(\s*(["'`])(.+?)\1/.exec(line)
        if (t) title = t[2]
        if (line.includes("// fixture-id")) return // a deliberately undefined id
        for (const id of new Set(line.match(idRe) ?? [])) {
          const slot = cites.get(id) ?? {}
          const where = `${relative(proto, f)}:${i + 1}`
          if (!slot[side]) slot[side] = side === "test" && title ? `${where} “${title}”` : where
          cites.set(id, slot)
        }
      })
    }
  }
  return { defined, cites }
}

const series = (id) => id.split("-").slice(0, 2).join("-")
const key = (id) => { const [k, p, n] = id.split("-"); return `${k}-${p}-${n.padStart(4, "0")}` }

export function render({ defined, cites }) {
  const ids = [...defined].sort((a, b) => (series(a) === series(b) ? key(a).localeCompare(key(b)) : a.localeCompare(b)))
  const status = (id) => { const c = cites.get(id); return c?.test ? "Tested" : c?.src ? "Prototyped" : "Specified" }
  const counts = {}
  for (const id of ids) {
    const s = series(id); counts[s] ??= { total: 0, cited: 0 }
    counts[s].total++; if (status(id) !== "Specified") counts[s].cited++
  }
  const head = Object.entries(counts).map(([s, c]) => `| ${s} | ${c.cited} | ${c.total} |`).join("\n")
  const rows = ids.map((id) => {
    const c = cites.get(id) ?? {}
    return `| ${id} | ${status(id)} | ${c.src ?? "—"} | ${c.test ?? "—"} |`
  }).join("\n")
  return `# Appendix — Spec-to-code correspondence

> **Document Control**
>
> | Property       | Value                                                        |
> | -------------- | ------------------------------------------------------------ |
> | Document ID    | BRIDGER-APP-04                                               |
> | Revision       | 0.1                                                          |
> | Effective Date | — (pending approval)                                         |
> | Status         | Draft                                                        |
> | Author         | Bridger Engineering                                          |
> | Reviewed by    | — (no independent reviewer yet; see PROC-03 §5)              |
> | Approved by    | — (pending; single maintainer, see PROC-03 §5)               |
> | Classification | Appendix — Informative                                       |
> | Change History | 0.1 (2026-11-22): Generated by \`prototypes/host-core/scripts/gen-correspondence.mjs\` (improvement report 07, R2) |

---

Generated by \`prototypes/host-core/scripts/gen-correspondence.mjs\` from the ids named in \`prototypes/host-core/{src,test}\`. Do not edit.
A behaviour or invariant is *Tested* when a test names it, *Prototyped* when only \`src/\` names it, *Specified* otherwise.
The prototype is not evidence for any requirement (CCR-BR-004); a citation says where to look, not that the rule holds.

## Coverage by series

| Series | Named in the prototype | Defined |
| --- | --- | --- |
${head}

## Every behaviour and invariant

| Id | Status | First in src | First in test |
| --- | --- | --- | --- |
${rows}
`
}

export const dangling = ({ defined, cites }) =>
  [...cites].filter(([id]) => !defined.has(id)).map(([id, c]) => `dangling id ${id} (${c.src ?? c.test})`)

export function check() {
  const data = collect()
  const fails = []
  fails.push(...dangling(data))
  if (!existsSync(out) || readFileSync(out, "utf8") !== render(data)) fails.push("references/core/appendices/correspondence.md is stale: run node scripts/gen-correspondence.mjs")
  const base = existsSync(baselinePath) ? JSON.parse(readFileSync(baselinePath, "utf8")) : {}
  const now = counts(data)
  for (const [s, n] of Object.entries(base)) if ((now[s] ?? 0) < n) fails.push(`coverage of ${s} fell from ${n} to ${now[s] ?? 0}`)
  return { fails, now, data }
}

function counts({ defined, cites }) {
  const c = {}
  for (const id of defined) if (cites.has(id)) c[series(id)] = (c[series(id)] ?? 0) + 1
  return c
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const arg = process.argv[2]
  if (arg === "--check") {
    const { fails, now } = check()
    const total = Object.values(now).reduce((a, b) => a + b, 0)
    console.log(`correspondence: ${total} ids named, ${Object.keys(now).length} series`)
    for (const f of fails) console.log(`FAIL ${f}`)
    console.log(`${fails.length} failure(s)`)
    process.exit(fails.length ? 1 : 0)
  }
  const data = collect()
  writeFileSync(out, render(data))
  if (arg === "--ratchet") writeFileSync(baselinePath, JSON.stringify(counts(data), null, 2) + "\n")
}
